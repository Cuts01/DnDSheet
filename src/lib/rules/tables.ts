/* Pact Magic: cantidad de slots y nivel de slot por nivel de Warlock. */
export function pactTable(warlockLevel: number): { count: number; slotLevel: number } {
  if (warlockLevel <= 0) return { count: 0, slotLevel: 0 };
  const count = warlockLevel === 1 ? 1 : warlockLevel <= 10 ? 2 : warlockLevel <= 16 ? 3 : 4;
  const slotLevel = Math.min(5, Math.ceil(warlockLevel / 2));
  return { count, slotLevel };
}
